#!/usr/bin/env python3
"""No-hallucination acceptance comparison for pinned 24k Loghub records."""
import hashlib,json,os
from pathlib import Path

STATE=Path(os.environ.get('PARSER_STUDIO_IRREGULAR_ROOT',
 '/home/aella/.local/state/parserstudio-irregular-20261024'))
def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def source(name):
 p=STATE/name
 return json.loads(p.read_text()),digest(p)
def main():
 before,bsha=source('pre-change-multipass.json')
 after,asha=source('candidate-multipass.json')
 api,apisha=source('api-qualified.json')
 assert before['upstreamCommit']==after['upstreamCommit']==api['upstream']
 assert len(before['datasets'])==len(after['datasets'])==12
 b=before['totals'];a=after['totals']
 for field in ('physical_lines','processed_events','raw_source_bytes','byte_accounted_ok'):
  assert a[field]==b[field],field
 assert b['processed_events']==a['processed_events']==24000
 assert a.get('parse_or_accounting_exceptions',0)==b.get('parse_or_accounting_exceptions',0)==0
 assert a['status_SOURCE_PARSED']==b['status_SOURCE_PARSED']
 assert a['status_RAW_ONLY']<b['status_RAW_ONLY']
 assert a['needs_semantic_or_grammar_review']==24000
 assert a['source_occurrence_spans']>b['source_occurrence_spans']
 assert a['unparsed_residual_bytes']<b['unparsed_residual_bytes']
 immutable={'OpenSSH','Linux','Apache','OpenStack','Hadoop','Zookeeper','BGL','Mac','Spark'}
 rows=[]
 for old,new in zip(before['datasets'],after['datasets']):
  assert old['dataset']==new['dataset']
  assert old['sourceSha256']==new['sourceSha256']
  if old['dataset'] in immutable:
   assert old['counts']==new['counts'],old['dataset']+' count drift'
   assert old['syntaxTop']==new['syntaxTop'],old['dataset']+' syntax drift'
  rows.append({'dataset':old['dataset'],'events':old['counts']['physical_lines'],
   'raw_sha256':old['sourceSha256'],
   'rawOnly_before':old['counts'].get('status_RAW_ONLY',0),
   'rawOnly_after':new['counts'].get('status_RAW_ONLY',0),
   'partial_before':old['counts'].get('status_PARTIAL',0),
   'partial_after':new['counts'].get('status_PARTIAL',0),
   'sourceParsed_before':old['counts'].get('status_SOURCE_PARSED',0),
   'sourceParsed_after':new['counts'].get('status_SOURCE_PARSED',0)})
 assert len(api['datasets'])==2
 api_fields=sum(x['counts'].get('independently_checked_field_occurrence',0) for x in api['datasets'])
 api_events=sum(x['events'] for x in api['datasets'])
 assert api_fields==19875 and api_events==4000
 assert all(x['mismatches']==0 for x in api['datasets'])
 assert all(x['counts']['frame_and_sha_ok']==2000 for x in api['datasets'])
 report={
 'contract':'parserstudio.loghub.corpus-delta.v0.1',
 'nature':'source structure only, not semantic/full-native/model success',
 'externalChatGPTProviderCalls':0,
 'manufacturerDeviceCaptures':0,
 'underlyingRawLogEvents':24000,
 'originalRawBytes':b['raw_source_bytes'],
 'byteAccountedBefore':b['byte_accounted_ok'],
 'byteAccountedAfter':a['byte_accounted_ok'],
 'parseExceptionsBefore':b.get('parse_or_accounting_exceptions',0),
 'parseExceptionsAfter':a.get('parse_or_accounting_exceptions',0),
 'sourceParsedBefore':b['status_SOURCE_PARSED'],
 'sourceParsedAfter':a['status_SOURCE_PARSED'],
 'partialBefore':b['status_PARTIAL'],
 'partialAfter':a['status_PARTIAL'],
 'rawOnlyBefore':b['status_RAW_ONLY'],
 'rawOnlyAfter':a['status_RAW_ONLY'],
 'rawOnlyReducedBy':b['status_RAW_ONLY']-a['status_RAW_ONLY'],
 'occurrenceSpansBefore':b['source_occurrence_spans'],
 'occurrenceSpansAfter':a['source_occurrence_spans'],
 'occurrenceSpansAdded':a['source_occurrence_spans']-b['source_occurrence_spans'],
 'unparsedResidualBytesBefore':b['unparsed_residual_bytes'],
 'unparsedResidualBytesAfter':a['unparsed_residual_bytes'],
 'unparsedResidualBytesReducedBy':b['unparsed_residual_bytes']-a['unparsed_residual_bytes'],
 'semanticOrGrammarReviewAfter':a['needs_semantic_or_grammar_review'],
 'independentFormatBatchEvents':api_events,
 'independentSourceValueAndOffsetChecks':api_fields,
 'independentSourceValueAndOffsetMismatches':0,
 'referenceEvidence':{
  'originalBenchmarkSha256':bsha,'candidateBenchmarkSha256':asha,
  'apiBenchmarkSha256':apisha,'loghubCommit':before['upstreamCommit']},
 'perDataset':rows,
 'disclaimer':'No native target/DP/sensor tests. ParserRecipe generated by independent external ChatGPT model not evaluated.'
 }
 target=STATE/'delta-evidence.json'
 target.write_text(json.dumps(report,indent=2)+'\n')
 print('QUALIFIED_24K_DELTA',json.dumps({k:report[k] for k in (
 'underlyingRawLogEvents','rawOnlyBefore','rawOnlyAfter','rawOnlyReducedBy',
 'occurrenceSpansAdded','unparsedResidualBytesReducedBy','sourceParsedBefore',
 'sourceParsedAfter','independentSourceValueAndOffsetChecks',
 'independentSourceValueAndOffsetMismatches')}))
 print('EVIDENCE_SHA256',digest(target))

if __name__=='__main__':main()
