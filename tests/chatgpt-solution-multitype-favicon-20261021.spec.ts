import {test,expect} from '@playwright/test';

test('ChatGPT Assisted preserves reviewed multi-type solution context and serves the real favicon',async({page,request})=>{
  const logA='event_type=threat action=deny src_ip=10.77.88.99 dst_port=443 threat_score=7';
  const logB='event_type=user action=login src_ip=10.77.88.98 dst_port=443 username=alice';
  await page.goto('/?workspace=chatgpt');
  await expect(page.getByRole('main',{name:'ChatGPT Assisted Parser'})).toBeVisible();
  await page.getByLabel('ChatGPT local sample logs').fill(logA);
  await page.getByRole('button',{name:'Add Another Log Type'}).click();
  await page.getByLabel('Log type name 1').fill('Threat');
  await page.getByLabel('Log type name 2').fill('User');
  await page.getByLabel('Log type sample 2').fill(logB);
  await page.getByLabel('ChatGPT solution vendor').fill('Example Network Vendor');
  await page.getByLabel('ChatGPT solution product').fill('Unified Security Gateway');
  await page.getByLabel('ChatGPT solution version or model').fill('Firmware 42.1');
  await page.getByLabel('ChatGPT log source or delivery').fill('Syslog / local export');
  const original=page.getByLabel('ChatGPT local sample logs');
  await expect(original).toHaveAttribute('readonly','');
  expect(await original.inputValue()).toContain(logA);
  expect(await original.inputValue()).toContain(logB);
  await expect(page.getByLabel('ChatGPT sharing example 1')).toHaveCount(0);
  await expect(page.getByLabel('ChatGPT sharing example 2')).toHaveCount(0);
  await expect(page.getByRole('alert').filter({hasText:'The ChatGPT prompt includes your original log text'})).toBeVisible();
  const prepare=page.getByRole('button',{name:'Prepare ChatGPT Prompt'});
  await expect(prepare).toBeEnabled({timeout:15000});
  await prepare.click();
  const prompt=page.getByLabel('ChatGPT copyable prompt');
  await expect(prompt).toBeVisible({timeout:15000});
  const text=await prompt.inputValue();
  expect(text).toContain('Unified Security Gateway');
  expect(text).toContain('Firmware 42.1');
  expect(text).toContain('"name":"Threat"');
  expect(text).toContain('"name":"User"');
  expect(text).toContain('reject-unknown behavior');
  expect(text).toContain('10.77.88.99');
  expect(text).toContain('10.77.88.98');
  await page.getByRole('button',{name:'Review shared extraction format in Auto Parser'}).click();
  await page.getByRole('button',{name:'ChatGPT Assisted Parser'}).click();
  await expect(page.getByLabel('ChatGPT solution vendor')).toHaveValue('Example Network Vendor');
  await expect(page.getByLabel('ChatGPT sharing example 1')).toHaveCount(0);
  const icon=await request.get('/favicon.svg');
  expect(icon.status()).toBe(200);
  expect(icon.headers()['content-type']).toContain('image/svg+xml');
  expect(await icon.text()).toContain('Parser Studio');
});
