/**
 * R5: one immutable deployable artifact assembled from the actual Web quality
 * job outputs. This does not trigger a build or run customer/target parsers.
 * Consumers must verify the downloaded bytes against this manifest and the
 * exact protected source HEAD before an independently approved rollout.
 */
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {existsSync,readFileSync,readdirSync,lstatSync,mkdirSync,copyFileSync,writeFileSync} from 'node:fs';
import {resolve,join,dirname,sep} from 'node:path';
import {pathToFileURL} from 'node:url';

export const CONTRACT='parser-studio.build-once-distribution.v1';
const ROOTS=Object.freeze({web:'dist',backend:'backend/dist',multipass:'runtime/multipass'});
const REQUIRED=[
 'web/index.html',
 'backend/src/mainline-authoring-server.js',
 'backend/semantic-policy.v1.json',
 'multipass/multipass_preview_api.py',
 'multipass/semantic-policy.v1.json',
];
const GIT_OID=/^(?:[a-f0-9]{40}|[a-f0-9]{64})$/;
const SHA256=/^[a-f0-9]{64}$/;
const BAD_SEGMENTS=new Set(['node_modules','__pycache__','.git','.env','secrets','credentials']);
const MAX_FILE_COUNT=512;
const MAX_MANIFEST_BYTES=256*1024;
const sha=(bytes)=>createHash('sha256').update(bytes).digest('hex');
function guard(ok,code){if(!ok)throw new Error(code);}
function sourceMetadata(root,head,tree){
 guard(GIT_OID.test(head)&&GIT_OID.test(tree),'BUILD_ONCE_BAD_SOURCE_ID');
 const policy=sha(readFileSync(join(root,'runtime/multipass/semantic-policy.v1.json')));
 return {
  sourceHead:head,sourceTree:tree,
  frontendLockSha256:sha(readFileSync(join(root,'package-lock.json'))),
  backendLockSha256:sha(readFileSync(join(root,'backend/package-lock.json'))),
  semanticPolicySha256:policy,
 };
}
function guardName(name){
 const parts=name.split('/');
 guard(parts.length>1&&parts.every(p=>p&&!BAD_SEGMENTS.has(p)&&!p.startsWith('.')) &&
   !name.includes('\\')&&!name.includes('..'),'BUILD_ONCE_UNSAFE_PATH');
}
/** Runtime bundle has only distributable build files; generated byte identities
 * are neither copied from historical reference receipts nor rebuilt here. */
function scan(root,section,{ignorePythonCache=false}={}){
 const items=[];
 const visit=(dir,sub='')=>{
  for(const ent of readdirSync(dir,{withFileTypes:true})){
   const rel=sub?sub+'/'+ent.name:ent.name;
   const full=join(dir,ent.name);
   // Python may have generated bytecode while CI tested source policy;
   // these cache directories are never deployment inputs or manifest entries.
   if(ignorePythonCache&&section==='multipass'&&ent.name==='__pycache__'&&
      ent.isDirectory())continue;
   guardName(section+'/'+rel);
   const st=lstatSync(full);
   guard(!st.isSymbolicLink(),'BUILD_ONCE_SYMLINK');
   if(st.isDirectory()){
    if(section==='multipass')throw new Error('BUILD_ONCE_MULTIPASS_RUNTIME_NESTING');
    visit(full,rel);
   }else{
    guard(st.isFile(),'BUILD_ONCE_UNSUPPORTED_FILE');
    if(section==='multipass'&&!/\.(py|json)$/.test(rel))
      throw new Error('BUILD_ONCE_NON_RUNTIME_MULTIPASS_FILE');
    items.push({source:full,logical:section+'/'+rel});
   }
  }
 };
 visit(root);
 return items;
}
export function createBuildOnceArtifact({root,bundle,head,tree}){
 root=resolve(root);bundle=resolve(bundle);
 guard(!existsSync(bundle),'BUILD_ONCE_BUNDLE_ALREADY_EXISTS');
 guard(!bundle.startsWith(root+sep),'BUILD_ONCE_OUTPUT_INSIDE_SOURCE');
 const metadata=sourceMetadata(root,head,tree);
 const files=[];
 for(const [section,path] of Object.entries(ROOTS)){
  const base=join(root,path);
  guard(existsSync(base),'BUILD_ONCE_MISSING_BUILT_TREE');
  const st=lstatSync(base);
  guard(st.isDirectory()&&!st.isSymbolicLink(),'BUILD_ONCE_SOURCE_ROOT_SYMLINK');
  files.push(...scan(base,section,{ignorePythonCache:true}));
 }
 files.sort((a,b)=>a.logical.localeCompare(b.logical,'en'));
 const actual=new Set(files.map(file=>file.logical));
 for(const name of REQUIRED)guard(actual.has(name),'BUILD_ONCE_REQUIRED_FILE_MISSING');
 guard(files.length>=REQUIRED.length&&files.length<=MAX_FILE_COUNT,
  'BUILD_ONCE_FILE_COUNT_OUTSIDE_BOUNDS');
 mkdirSync(bundle,{recursive:false,mode:0o700});
 const contents={};
 for(const file of files){
  const bytes=readFileSync(file.source);
  guard(bytes.byteLength>0&&bytes.byteLength<=8*1024*1024,'BUILD_ONCE_UNSAFE_FILE_SIZE');
  const dest=join(bundle,file.logical);
  mkdirSync(dirname(dest),{recursive:true});
  copyFileSync(file.source,dest);
  guard(sha(readFileSync(dest))===sha(bytes),'BUILD_ONCE_STAGING_DRIFT');
  contents[file.logical]={bytes:bytes.byteLength,sha256:sha(bytes)};
 }
 guard(contents['backend/semantic-policy.v1.json'].sha256===metadata.semanticPolicySha256,
  'BUILD_ONCE_BACKEND_POLICY_DRIFT');
 const manifest={
  contract:CONTRACT,...metadata,
  distributionProducer:'web-quality-after-exact-head-frontend-and-backend-build',
  generatedArtifacts:false,
  customerDataIncluded:false,
  targetImportVerified:false,
  indexedEventVerified:false,
  deployPerformed:false,
  fileCount:files.length,
  fileIndex:contents,
 };
 writeFileSync(join(bundle,'manifest.json'),JSON.stringify(manifest,null,2)+'\n',{flag:'wx'});
 return manifest;
}
export function verifyBuildOnceArtifact({root,bundle,head,tree}){
 root=resolve(root);bundle=resolve(bundle);
 const st=lstatSync(bundle);
 guard(st.isDirectory()&&!st.isSymbolicLink(),'BUILD_ONCE_BUNDLE_NOT_DIR');
 const manifestFile=join(bundle,'manifest.json');
 const manifestStat=lstatSync(manifestFile);
 guard(manifestStat.isFile()&&!manifestStat.isSymbolicLink()&&
  manifestStat.size<=MAX_MANIFEST_BYTES,'BUILD_ONCE_UNSAFE_MANIFEST');
 const manifest=JSON.parse(readFileSync(manifestFile,'utf8'));
 const metadata=sourceMetadata(root,head,tree);
 guard(manifest.contract===CONTRACT,'BUILD_ONCE_BAD_CONTRACT');
 guard(manifest.distributionProducer===
  'web-quality-after-exact-head-frontend-and-backend-build','BUILD_ONCE_BAD_PRODUCER');
 for(const [k,v] of Object.entries(metadata))
  guard(manifest[k]===v,'BUILD_ONCE_SOURCE_OR_POLICY_MISMATCH_'+k);
 guard(manifest.generatedArtifacts===false&&manifest.customerDataIncluded===false&&
   manifest.targetImportVerified===false&&manifest.indexedEventVerified===false&&
   manifest.deployPerformed===false,'BUILD_ONCE_FORGED_TARGET_PROOF');
 const expectedKeys=['contract',...Object.keys(metadata),'distributionProducer',
  'generatedArtifacts','customerDataIncluded','targetImportVerified',
  'indexedEventVerified','deployPerformed','fileCount','fileIndex'];
 guard(Object.keys(manifest).sort().join(',')===expectedKeys.sort().join(','),
  'BUILD_ONCE_UNKNOWN_MANIFEST_FIELDS');
 guard(manifest.fileIndex&&typeof manifest.fileIndex==='object'&&
  !Array.isArray(manifest.fileIndex),'BUILD_ONCE_BAD_INDEX');
 const fileNames=Object.keys(manifest.fileIndex).sort();
 guard(manifest.fileCount===fileNames.length&&fileNames.length>=REQUIRED.length&&
  fileNames.length<=MAX_FILE_COUNT,
  'BUILD_ONCE_FILE_COUNT_MISMATCH');
 for(const name of REQUIRED)guard(fileNames.includes(name),'BUILD_ONCE_REQUIRED_FILE_MISSING');
 const seen=[];
 for(const [section] of Object.entries(ROOTS)){
  const dir=join(bundle,section);
  guard(existsSync(dir),'BUILD_ONCE_MISSING_PART');
  const st=lstatSync(dir);
  guard(st.isDirectory()&&!st.isSymbolicLink(),'BUILD_ONCE_BUNDLE_ROOT_SYMLINK');
  seen.push(...scan(dir,section).map(x=>x.logical));
 }
 guard(seen.sort().join('\n')===fileNames.join('\n'),'BUILD_ONCE_UNDECLARED_OR_MISSING_FILE');
 for(const name of fileNames){
  guardName(name);
  const record=manifest.fileIndex[name];
  guard(record&&Object.keys(record).sort().join(',')==='bytes,sha256'&&
   Number.isSafeInteger(record.bytes)&&record.bytes>0&&
   record.bytes<=8*1024*1024&&SHA256.test(record.sha256),
    'BUILD_ONCE_BAD_FILE_RECORD');
  const bytes=readFileSync(join(bundle,name));
  guard(bytes.byteLength===record.bytes&&sha(bytes)===record.sha256,
   'BUILD_ONCE_FILE_HASH_MISMATCH_'+name);
 }
 guard(manifest.fileIndex['backend/semantic-policy.v1.json'].sha256===
  metadata.semanticPolicySha256,'BUILD_ONCE_BACKEND_POLICY_DRIFT');
 guard(readdirSync(bundle).sort().join(',')==='backend,manifest.json,multipass,web',
   'BUILD_ONCE_EXTRA_ROOT_ARTIFACT');
 return {sourceHead:manifest.sourceHead,fileCount:fileNames.length,
  distributionSha256:sha(readFileSync(join(bundle,'manifest.json')))};
}
function git(root,...args){
 return execFileSync('git',['-C',root,...args],{encoding:'utf8'}).trim();
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
 try{
  const mode=process.argv[2],bundle=process.argv[3],root=process.cwd();
  guard((mode==='create'||mode==='verify')&&typeof bundle==='string'&&bundle.length>1,
   'BUILD_ONCE_USAGE');
  const head=git(root,'rev-parse','HEAD');
  const tree=git(root,'rev-parse','HEAD^{tree}');
  const expected=process.env.PARSER_STUDIO_EXPECTED_SOURCE_HEAD;
  guard(!expected||expected===head,'BUILD_ONCE_WRONG_SOURCE_HEAD');
  // The producer must be bound to the reviewed source tree, not post-test
  // edits or a local dirty build whose commit SHA is misleading.
  const modified=git(root,'status','--porcelain','--untracked-files=no');
  guard(!modified,'BUILD_ONCE_DIRTY_SOURCE');
  const result=mode==='create'
   ?createBuildOnceArtifact({root,bundle,head,tree})
   :verifyBuildOnceArtifact({root,bundle,head,tree});
  console.log('BUILD_ONCE_'+mode.toUpperCase()+'_PASS '+JSON.stringify({
   sourceHead:head,files:mode==='create'?result.fileCount:result.fileCount,
   ...(mode==='verify'?{distributionSha256:result.distributionSha256}:{}),
  }));
 }catch(error){
  console.error(error instanceof Error?error.message:'BUILD_ONCE_UNKNOWN_ERROR');
  process.exitCode=1;
 }
}
