"""Prepare one owner-approved *synthetic* host-reference parser pair for a POC CRUD test.

Only inputs are reviewed synthetic artifacts generated by Parser Studio backend
native test suite. They are not signed Stellar Cyber compatibility fixtures.
No user logs, downloaded vendor parsers, or arbitrary Ruby are ever accepted.
"""

import base64
import hashlib
import json
import os
from pathlib import Path
import re
import stat

FIXTURE_DIR = Path.home() / ".cache/parser-studio-poc-crud-fixtures"
FIXTURE_NAME = "customized_sample_syslog"
FIXTURE_HASHES = {
    FIXTURE_NAME: "d5e025b2f1792567113246888f0b87e512dab43934279dfd22b19259c374a873",
    FIXTURE_NAME + ".conf": "0ebcd7c8a50ac016b994cf7a3efb9c920b50d9ae4d400fb6a7f753ce9e0e4ee7",
}
FIXTURE_PORT = 7123
TEST_NAME_RE = re.compile(r"customized_ps_api_crud_test_[0-9a-f]{6,16}\Z")


class InvalidSyntheticFixture(ValueError):
    pass


def load_verified_fixture(filename):
    if filename not in FIXTURE_HASHES:
        raise InvalidSyntheticFixture("Non-allowlisted synthetic parser fixture")
    # Cache directory and file are private; avoid following unexpected symbolic
    # links. The attested SHA is verified again on each load.
    parent = FIXTURE_DIR.lstat()
    if (not stat.S_ISDIR(parent.st_mode) or parent.st_uid != os.getuid()
            or stat.S_IMODE(parent.st_mode) != 0o700):
        raise InvalidSyntheticFixture("Unexpected synthetic fixture directory")
    path = FIXTURE_DIR / filename
    flags = os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC
    fd = os.open(path, flags)
    try:
        info = os.fstat(fd)
        if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid()
                or stat.S_IMODE(info.st_mode) != 0o600 or info.st_size > 200_000):
            raise InvalidSyntheticFixture("Unexpected synthetic fixture permissions/size")
        with os.fdopen(fd, "rb") as f:
            fd = -1
            body = f.read(200_001)
    finally:
        if fd >= 0:
            os.close(fd)
    if hashlib.sha256(body).hexdigest() != FIXTURE_HASHES[filename]:
        raise InvalidSyntheticFixture("Synthetic fixture SHA mismatch")
    return body.decode("utf-8")


def make_host_parser_pair(name, port, version):
    if not TEST_NAME_RE.fullmatch(name):
        raise InvalidSyntheticFixture("Refusing non-test parser name")
    if not 7800 <= port <= 7999:
        raise InvalidSyntheticFixture("Unexpected test-only port")
    if version not in ("1.0.0", "1.0.1"):
        raise InvalidSyntheticFixture("Unexpected test-only version")

    ruby = load_verified_fixture(FIXTURE_NAME)
    conf = load_verified_fixture(FIXTURE_NAME + ".conf")

    # The existing POC parser metadata confirms 'customized_*' as parser_name
    # and two files whose names are exactly parser_name, parser_name+'.conf'.
    # The host reference artifact ships a Ruby body without an extension.
    if "STELLAR_INIT_BEGIN" not in ruby or "STELLAR_PARSE_BEGIN" not in ruby:
        raise InvalidSyntheticFixture("Not a reviewed Parser Studio synthetic Ruby fragment")
    if conf.count("port 7123") != 2 or conf.count(FIXTURE_NAME) < 4:
        raise InvalidSyntheticFixture("Unexpected synthetic Fluentd configuration contract")

    conf = conf.replace(FIXTURE_NAME, name).replace("port 7123", f"port {port}")

    # Keep synthetic in-memory receiver settings internally consistent with
    # the external CONF port and parser slug. Decode and reencode only the
    # known initializer's embedded synthetic fixture object.
    match = re.search(r"Base64\.strict_decode64\('([A-Za-z0-9+/=]+)'\)", ruby)
    if match is None:
        raise InvalidSyntheticFixture("Synthetic initializer not found")
    try:
        project = json.loads(base64.b64decode(match.group(1), validate=True))
    except (ValueError, TypeError):
        raise InvalidSyntheticFixture("Synthetic initializer does not decode") from None
    if project.get("receiver", {}).get("port") != FIXTURE_PORT:
        raise InvalidSyntheticFixture("Unexpected synthetic receiver port")
    project["receiver"]["port"] = port
    project["slug"] = name[len("customized_"):]
    encoded = base64.b64encode(json.dumps(project, separators=(",", ":")).encode()).decode("ascii")
    ruby = ruby.replace(match.group(1), encoded, 1)

    if f"@type {name}" not in conf or f"port {port}" not in conf:
        raise InvalidSyntheticFixture("Synthetic naming conversion failed")
    return [
        ("file", (name, ruby.encode("utf-8"), "application/octet-stream")),
        ("file", (name + ".conf", conf.encode("utf-8"), "text/plain")),
    ]
